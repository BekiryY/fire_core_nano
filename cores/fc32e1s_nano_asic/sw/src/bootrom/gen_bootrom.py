#!/usr/bin/env python3
"""gen_bootrom.py <bin> <out.sv> <source name> -- boot ROM image -> SV constant table (32 words).

The table is a constant array indexed by the registered word index, not a case statement:
Yosys turns a case table into a ROM and merges the index register into it, which costs
one flip-flop per non-constant data bit (26) instead of the 5 index bits (measured, sky130 hd:
fetch port 1519 um2 with the case table, 963 um2 with the array)."""
import sys

WORDS = 32
MODULE = "fc32e1s_nano_sram2k_v2_bootrom"
data = open(sys.argv[1], "rb").read()
data += bytes(-len(data) % 4)
words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
if len(words) > WORDS:
    sys.exit(f"boot ROM image is {len(words) * 4} bytes, max {WORDS * 4}")
words += [0] * (WORDS - len(words))

lines = [
    f"// {MODULE}.sv -- GENERATED by sw/src/bootrom/build_bootrom.sh from {sys.argv[3]}; do not edit.",
    "// Boot ROM of the v2 hard macro: 32 words at fetch address 0x000 - 0x07F, combinational",
    "// (word index in, word out). Unused words read 0 (illegal instruction).",
    "",
    f"module {MODULE} (",
    "  input  logic [4:0]  addr_i,     // word index",
    "  output logic [31:0] data_o",
    ");",
    "",
    f"  localparam logic [31:0] ROM [{WORDS}] = '{{",
]
for i, w in enumerate(words):
    sep = "," if i < WORDS - 1 else ""
    lines.append(f"    32'h{w >> 16:04x}_{w & 0xFFFF:04x}{sep}   // {i:2d}")
lines += [
    "  };",
    "",
    "  assign data_o = ROM[addr_i];",
    "",
    "endmodule",
    "",
]
open(sys.argv[2], "w", newline="\n").write("\n".join(lines))
print(f"{sys.argv[2]}: {len([w for w in words if w])} of {WORDS} words used")
